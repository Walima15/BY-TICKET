#!/usr/bin/env node
// Generate apps/web/src/lib/supabase/database.types.ts from supabase/migrations without a Supabase
// project: start the throwaway `db-test` Postgres with the migrations applied, then run Supabase's
// own generator (postgres-meta, what `supabase gen types` uses) against it.
// Usage (repo root): npm run db:types
import { spawn, spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "apps/web/src/lib/supabase/database.types.ts");
const container = "by-db-types";
const port = 54329;
const pgMetaImage = "supabase/postgres-meta:v0.91.6";

function docker(args, opts = {}) {
  const r = spawnSync("docker", args, { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024, ...opts });
  if (r.status !== 0) throw new Error(`docker ${args.join(" ")} failed:\n${r.stderr || r.stdout}`);
  return r.stdout;
}

function waitForReady() {
  return new Promise((resolve, reject) => {
    const logs = spawn("docker", ["logs", "-f", container]);
    let buf = "";
    const timer = setTimeout(() => {
      logs.kill();
      reject(new Error(`database did not become ready:\n${buf}`));
    }, 120_000);
    const onData = (chunk) => {
      buf += chunk;
      if (buf.includes("database ready")) {
        clearTimeout(timer);
        logs.kill();
        resolve();
      } else if (/ERROR:/.test(buf)) {
        clearTimeout(timer);
        logs.kill();
        reject(new Error(`migration failed:\n${buf}`));
      }
    };
    logs.stdout.on("data", onData);
    logs.stderr.on("data", onData);
  });
}

spawnSync("docker", ["rm", "-f", container], { stdio: "ignore" });
docker(["compose", "run", "-d", "--rm", "--name", container, "-p", `${port}:5432`, "-e", "KEEP_RUNNING=1", "db-test"]);
try {
  await waitForReady();
  const types = docker([
    "run", "--rm",
    "-e", `PG_META_DB_URL=postgresql://postgres@host.docker.internal:${port}/postgres`,
    "-e", "PG_META_GENERATE_TYPES=typescript",
    "-e", "PG_META_GENERATE_TYPES_INCLUDED_SCHEMAS=public",
    "-e", "PG_META_GENERATE_TYPES_DETECT_ONE_TO_ONE_RELATIONSHIPS=true",
    pgMetaImage, "node", "dist/server/server.js",
  ]);
  if (!types.includes("export type Database")) throw new Error(`unexpected generator output:\n${types.slice(0, 500)}`);
  const header = "// Generated by `npm run db:types` from supabase/migrations. Do not edit by hand.\n\n";
  writeFileSync(out, header + types.replace(/\r\n/g, "\n"));
  console.log(`wrote ${out}`);
} finally {
  spawnSync("docker", ["stop", container], { stdio: "ignore" });
}
